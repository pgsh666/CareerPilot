import { mkdir, readFile, writeFile } from "node:fs/promises";
import { h } from "vue";
import { renderToString } from "vue/server-renderer";
import * as outline from "@heroicons/vue/24/outline";
import * as solid from "@heroicons/vue/24/solid";

// Official Heroicons data. Only selected paths ship in the application.
const selected = {
  home: "HomeIcon",
  interview: "ChatBubbleLeftRightIcon",
  resume: "DocumentTextIcon",
  history: "ClockIcon",
  settings: "Cog6ToothIcon",
};
const directory = new URL("../src/ui/icons/heroicons/", import.meta.url);
await mkdir(directory, { recursive: true });
const icons = {};
for (const [name, component] of Object.entries(selected)) {
  icons[name] = {};
  for (const [style, collection] of Object.entries({ outline, solid })) {
    const svg = await renderToString(h(collection[component]));
    await writeFile(new URL(`${name}-${style}.svg`, directory), svg + "\n");
    const paths = [...svg.matchAll(/<path\b([^>]+)>/g)].map(([, markup]) => {
      const attributes = Object.fromEntries(
        [...markup.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [
          key,
          value,
        ]),
      );
      if (style === "solid")
        Object.assign(attributes, { fill: "currentColor", stroke: "none" });
      return ["path", attributes];
    });
    if (!paths.length) throw new Error(`No paths: ${name}-${style}`);
    icons[name][style] = paths;
  }
}
await writeFile(
  new URL("navigation.ts", directory),
  `// Generated by scripts/update-navigation-icons.mjs from @heroicons/vue 2.2.0.\n// Copyright (c) Tailwind Labs, Inc. MIT: see LICENSE.\nimport type { IconNode } from "morphicons/vue";\nexport const navigationIcons = ${JSON.stringify(icons, null, 2)} satisfies Record<string, { outline: IconNode; solid: IconNode }>;\n`,
);
await writeFile(
  new URL("LICENSE", directory),
  await readFile(
    new URL("../node_modules/@heroicons/vue/LICENSE", import.meta.url),
    "utf8",
  ),
);
await writeFile(
  new URL("SOURCE.md", directory),
  "Heroicons 2.2.0, selected from the libraries demonstrated at https://www.morphicons.com/.\n\nOfficial source: https://github.com/tailwindlabs/heroicons/tree/v2.2.0/optimized/24\n\nRegenerate the selected SVGs and icon data with `node scripts/update-navigation-icons.mjs`. The script uses the official Vue exports; only selected paths are bundled.\n\nMIT license: LICENSE.\n",
);
console.log(`Generated ${Object.keys(icons).length} navigation icon pairs.`);
